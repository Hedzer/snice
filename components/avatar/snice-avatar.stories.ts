// h2: Shape × Size Matrix
export const ShapeXSizeMatrix: Story = {
  render: () => {
    const grid = document.createElement('div');
    grid.style.cssText = 'display:grid;grid-template-columns:auto repeat(6,1fr);gap:.75rem;align-items:center;';
    for (const shape of SHAPES) {
      const lbl = document.createElement('div');
      lbl.style.cssText = 'font-size:.7rem;color:#888;text-align:right;padding-right:.5rem;';
      lbl.textContent = shape;
      grid.appendChild(lbl);
      for (const size of SIZES) {
        grid.appendChild(makeAvatar({ shape, size, name: 'AL' }));
      }
    }
    return grid;
  },
};

