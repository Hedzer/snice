import type { Meta, StoryObj } from '@storybook/html-vite';
import './snice-avatar';
import type { AvatarSize, AvatarShape } from './snice-avatar.types';

type Args = {
  src?: string;
  alt?: string;
  name?: string;
  size?: AvatarSize;
  shape?: AvatarShape;
  fallbackColor?: string;
  fallbackBackground?: string;
};

const SIZES: AvatarSize[] = ['xs', 'small', 'medium', 'large', 'xl', 'xxl'];
const SHAPES: AvatarShape[] = ['circle', 'square', 'rounded'];

function makeAvatar(attrs: Record<string, string> = {}): HTMLElement {
  const el = document.createElement('snice-avatar');
  for (const [k, v] of Object.entries(attrs)) {
    el.setAttribute(k, v);
  }
  return el;
}

function row(...els: HTMLElement[]): HTMLElement {
  const wrap = document.createElement('div');
  wrap.style.cssText = 'display:flex;align-items:center;gap:.75rem;flex-wrap:wrap;';
  els.forEach(el => wrap.appendChild(el));
  return wrap;
}

const meta: Meta<Args> = {
  title: 'Data/Avatar',
  component: 'snice-avatar',
  tags: ['autodocs'],
  argTypes: {
    src:                { control: 'text' },
    alt:                { control: 'text' },
    name:               { control: 'text' },
    size:               { control: 'select', options: SIZES },
    shape:              { control: 'select', options: SHAPES },
    fallbackColor:      { control: 'color' },
    fallbackBackground: { control: 'color' },
  },
  render: (args) => {
    const el = document.createElement('snice-avatar');
    if (args.src               !== undefined) el.setAttribute('src',                 args.src);
    if (args.alt               !== undefined) el.setAttribute('alt',                 args.alt);
    if (args.name              !== undefined) el.setAttribute('name',                args.name);
    if (args.size              !== undefined) el.setAttribute('size',                args.size);
    if (args.shape             !== undefined) el.setAttribute('shape',               args.shape);
    if (args.fallbackColor     !== undefined) el.setAttribute('fallback-color',      args.fallbackColor);
    if (args.fallbackBackground !== undefined) el.setAttribute('fallback-background', args.fallbackBackground);
    return el;
  },
};
export default meta;

type Story = StoryObj<Args>;

export const Default: Story = { args: { name: 'Ada Lovelace', size: 'medium', shape: 'circle' } };

// h2: All Sizes — Initials
export const AllSizesInitials: Story = {
  render: () => row(...SIZES.map(size => makeAvatar({ size, name: 'Ada Lovelace' }))),
};

